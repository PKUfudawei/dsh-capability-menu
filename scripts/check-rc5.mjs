import assert from 'node:assert/strict';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
if (!process.env.DSH_RUNTIME_MODULES) throw new Error('Set DSH_RUNTIME_MODULES to the installed rc.5 host node_modules directory');
const base=join(process.env.DSH_RUNTIME_MODULES,'@deepseek-ai');
const load=name=>import(pathToFileURL(join(base,name,'lib/index.js')).href);
const {Context}=await load('cordis');
const {LlmAdapter,createUserMessage}=await load('dsh-llm');
const policy=await import('../lib/policy.js');
const registry=await import('../lib/registry.js');
const search=await import('../lib/search.js');
const ctx=new Context();
for(const name of ['dsh-llm','dsh-session','dsh-session-projection','dsh-system-prompt','dsh-tools']) await ctx.plugin((await load(name)).default);
await ctx.plugin(await load('dsh-tool-executor-native'));
await ctx.plugin((await load('dsh-agent')).default);
await ctx.plugin((await load('dsh-skill')).default);
ctx.provide('workingDirectory',{ensure:async()=>'/tmp'});
await ctx.plugin(await load('dsh-tool-skill'));
for(const name of ['resident-skill','lazy-skill']) ctx.skills.register({name,description:name+' description',content:'Instruction body',source:'runtime'});
await ctx.plugin(registry,{stateFile:''});
await ctx.plugin(policy,{stateFile:'',skills:{'on-demand':['lazy-skill']}});
await ctx.plugin(search);
const requests=[];
class Adapter extends LlmAdapter { async *stream(request) {requests.push(request); yield {type:'block-start',index:0,blockType:'text'}; yield {type:'text-delta',index:0,text:'OK'}; yield {type:'block-end',index:0,block:{type:'text',text:'OK'}}; yield {type:'finish',reason:{kind:'stop'}};} }
ctx.llm.registerAdapter(['probe'],new Adapter());
await ctx.plugin((await load('dsh-agent-loop')).default,{agents:[]});
const agent=await ctx.agentLoop.create('catalog-integration',{provider:'probe',model:'probe'},{cwd:'/tmp',agentPreset:'catalog-mode'});
await ctx.capabilityPolicy.setOverrides('catalog-mode',[{kind:'skills',id:'lazy-skill',tier:'on-demand'}]);
async function turn(){
 const before=requests.length;
 agent.send(createUserMessage({source:{kind:'user'},content:[{type:'text',text:'hello'}]}),'next-turn',true);
 for(let i=0;i<200;i++){await new Promise(r=>setTimeout(r,10)); if(agent.status==='idle')break;}
 assert.equal(requests.length,before+1,JSON.stringify(agent.session.snapshotEvents().slice(-5)));
}
await turn();
await turn();
const catalogs=()=>agent.session.snapshotEvents().filter(e=>e.type==='user/message'&&e.data.source.kind==='skill-catalog');
assert.equal(catalogs().length,1);
assert.deepEqual(catalogs()[0].data.source.entries.map(e=>e.name),['resident-skill']);
assert(!JSON.stringify(requests[0].messages).includes('lazy-skill description'));
const tool=ctx.tools.get('meta_search',agent);
const found=await tool.execute({kind:'skill'},{agent,signal:new AbortController().signal});
assert(found.results.some(r=>r.id==='lazy-skill'));
await ctx.capabilityPolicy.setOverrides('catalog-mode',[{kind:'skills',id:'lazy-skill',tier:'resident'}]);
await turn();
assert.equal(catalogs().length,2);
assert.deepEqual(catalogs()[1].data.source.entries.map(e=>e.name),['lazy-skill','resident-skill']);
await ctx.capabilityPolicy.setOverrides('catalog-mode',[{kind:'skills',id:'lazy-skill',tier:'on-demand'}]);
await turn();
assert.equal(catalogs().length,3);
assert.deepEqual(catalogs()[2].data.source.entries.map(e=>e.name),['resident-skill']);
assert.equal(agent.session.snapshotEvents().filter(e=>e.type==='assistant/message').length,4);
const a=await ctx.agentLoop.create('preset-a',{provider:'probe',model:'probe'},{cwd:'/tmp',agentPreset:'a'});
const b=await ctx.agentLoop.create('preset-b',{provider:'probe',model:'probe'},{cwd:'/tmp',agentPreset:'b'});
await ctx.capabilityPolicy.setOverrides('a',[{kind:'skills',id:'lazy-skill',tier:'disabled'}]);
await ctx.capabilityPolicy.setOverrides('b',[{kind:'skills',id:'lazy-skill',tier:'on-demand'}]);
const [searchA,searchB]=await Promise.all([a,b].map(agent=>tool.execute({kind:'skill'},{agent,signal:new AbortController().signal})));
assert(!searchA.results.some(r=>r.id==='lazy-skill'));
assert(searchB.results.some(r=>r.id==='lazy-skill'));
console.log(JSON.stringify({host:'0.2.2-rc.5',realAgentLoop:true,requests:requests.length,catalogs:catalogs().length,metaSearch:'PASS',firstRequest:'PASS',deduplication:'PASS',tierUpdates:'PASS'}));
process.exit(0);
