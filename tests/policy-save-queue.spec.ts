import { afterEach, describe, expect, it, vi } from 'vitest'
import { PolicySaveQueue } from '../src/client/policy-save-queue.ts'
import type { PolicyChoice } from '../src/client/remote.ts'

const choice = (tier: PolicyChoice['tier'], id = 'skill'): PolicyChoice => ({ kind: 'skills', id, tier })
afterEach(() => vi.useRealTimers())
describe('debounced policy saves', () => {
  it('waits 1.5 seconds after the last click and batches final choices across rows', async () => {
    vi.useFakeTimers()
    const save = vi.fn(async () => {})
    const queue = new PolicySaveQueue(save, () => {})
    queue.enqueue([choice('resident')])
    await vi.advanceTimersByTimeAsync(1000)
    queue.enqueue([choice('disabled'), choice('on-demand', 'other')])
    await vi.advanceTimersByTimeAsync(1499)
    expect(save).not.toHaveBeenCalled()
    await vi.advanceTimersByTimeAsync(1)
    expect(save).toHaveBeenCalledExactlyOnceWith([choice('disabled'), choice('on-demand', 'other')])
    expect(queue.dirty).toBe(false)
  })
  it('serializes slow writes while accepting subsequent clicks', async () => {
    vi.useFakeTimers()
    let release!: () => void
    const save = vi.fn().mockImplementationOnce(() => new Promise<void>(resolve => { release = resolve }))
      .mockResolvedValue(undefined)
    const queue = new PolicySaveQueue(save, () => {})
    queue.enqueue([choice('resident')])
    await vi.advanceTimersByTimeAsync(1500)
    queue.enqueue([choice('disabled')])
    await vi.advanceTimersByTimeAsync(1500)
    expect(save).toHaveBeenCalledTimes(1)
    queue.enqueue([choice('on-demand')])
    release()
    await vi.advanceTimersByTimeAsync(1499)
    expect(save).toHaveBeenCalledTimes(1)
    await vi.advanceTimersByTimeAsync(1)
    expect(save).toHaveBeenLastCalledWith([choice('on-demand')])
    expect(queue.dirty).toBe(false)
  })
  it('retains failed changes without overwriting newer choices, then retries', async () => {
    vi.useFakeTimers()
    let reject!: (error: Error) => void
    const save = vi.fn().mockImplementationOnce(() => new Promise<void>((_, fail) => { reject = fail }))
      .mockResolvedValue(undefined)
    const queue = new PolicySaveQueue(save, () => {})
    queue.enqueue([choice('resident'), choice('disabled', 'other')])
    await vi.advanceTimersByTimeAsync(1500)
    queue.enqueue([choice('on-demand')])
    reject(new Error('offline'))
    await vi.advanceTimersByTimeAsync(0)
    expect(queue.error).toBeInstanceOf(Error)
    expect(queue.dirty).toBe(true)
    await queue.flush()
    expect(save).toHaveBeenLastCalledWith([choice('on-demand'), choice('disabled', 'other')])
    expect(queue.error).toBeNull()
    expect(queue.dirty).toBe(false)
  })
  it('flushes before the debounce deadline when the panel is left', async () => {
    vi.useFakeTimers()
    const save = vi.fn(async () => {})
    const queue = new PolicySaveQueue(save, () => {})
    queue.enqueue([choice('disabled')])
    await queue.flush()
    await vi.advanceTimersByTimeAsync(1500)
    expect(save).toHaveBeenCalledExactlyOnceWith([choice('disabled')])
  })
})
